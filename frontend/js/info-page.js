export function initializeInfoPage(settings = shopConfig) {
  config = settings;
  const root = document.querySelector("[data-info-page]");
  if (!root) return;
  const page = pages[root.dataset.infoPage];
  if (!page) return;
  document.title = page.title + " — " + config.name;
  const sourceLinks =
    root.dataset.infoPage === "delivery"
      ? '<nav class="info-source-links" aria-label="Офіційні тарифи"><a href="https://www.ukrposhta.ua/ua/taryfy-ukrposhta-priorytetnyi" target="_blank" rel="noopener noreferrer">Актуальні тарифи Укрпошти ↗</a><a href="https://novaposhta.ua/shipping-cost/?language=uk" target="_blank" rel="noopener noreferrer">Актуальні тарифи Нової пошти ↗</a></nav>'
      : "";
  const privacyLinks =
    root.dataset.infoPage === "privacy"
      ? '<p class="info-legal-link"><a href="https://zakon.rada.gov.ua/laws/show/2297-17" target="_blank" rel="noopener noreferrer">Закон України «Про захист персональних даних» ↗</a></p>'
      : "";
  root.innerHTML = `<div class="breadcrumbs"><a href="index.html">Головна</a><span>/</span><span>${safe(page.title)}</span></div><div class="page-title"><p class="eyebrow">NEXLAB / Покупцям</p><h1>${safe(page.title)}</h1><p>${safe(page.lead)}</p></div><div class="info-sections ${root.dataset.infoPage === "faq" ? "faq-list" : ""}">${page
    .sections()
    .map(
      ([heading, copy]) => root.dataset.infoPage === "faq"
        ? `<details class="faq-item"><summary>${safe(heading)}</summary><p>${safe(copy)}</p></details>`
        : `<section class="profile-panel"><h2>${safe(heading)}</h2><p>${heading === "Телефон" && config.supportPhone ? `<a href="tel:${safe(config.supportPhone)}">${safe(copy)}</a>` : heading === "Електронна пошта" && config.supportEmail ? `<a href="mailto:${safe(config.supportEmail)}">${safe(copy)}</a>` : safe(copy)}</p></section>`,
    )
    .join(
      "",
    )}</div>${privacyLinks}${sourceLinks}<nav class="info-links" aria-label="Інформація для покупців">${Object.entries(
    pages,
  )
    .map(([id, page]) => `<a href="${id}.html">${safe(page.title)}</a>`)
    .join("")}</nav>`;
}
